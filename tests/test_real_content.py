    def test_active_ranges_do_not_overlap_or_delete_objects(self):
        for doc in self.targets:
            owned=set()
            for p in sorted((p for p in self.active if p['target_id']==doc.hash),key=lambda p:p['start']):
                indices=set(range(p['start'],p['end']))
                self.assertFalse(indices & owned,p['id']);owned.update(indices)
                if p.get('action')=='source_merge':
                    for b in doc.blocks[p['start']:p['end']]:
                        self.assertEqual('paragraph',b.kind);self.assertFalse(b.images);self.assertFalse(b.heading)

    def test_analysis_does_not_mutate_original_inputs(self):
        for path,digest in self.original_hashes.items():
            self.assertEqual(digest,hashlib.sha256(Path(path).read_bytes()).hexdigest())

    def test_unresolved_decision_does_not_absorb_adjacent_protected_objects(self):
        from server import decision_members
        proposal=next(p for p in self.result['proposals']
                      if p['target_id']==self.first.hash and p['id'].endswith(':a35'))
        self.assertEqual('pending',proposal['decision'])
        self.assertEqual([proposal['id']],
                         [p['id'] for p in decision_members(self.result,proposal)])
        # Source-backed adjacent ranges remain grouped; unresolved/retained items
        # and protected images must be independently decidable.
        self.assertTrue(any(p.get('transaction_member_count',0)>1 for p in self.active))
        for item in self.result['proposals']:
            if item['decision'] not in ('accept','same'):
                self.assertEqual(1,item['transaction_member_count'],item['id'])



    def test_industry_merge_replaces_whole_new_paragraph_once(self):
        old=next(b for b in self.first.blocks if b.text.startswith('肉猪养殖产业是一个'))
        proposal=self.active_covering(self.first,old);self.assertEqual(1,len(proposal));proposal=proposal[0]
        c,texts=self.selected(proposal)
        expected=next(t for t in direct_paragraphs(self.source.path) if t.startswith('肉猪养殖产业是一个'))
        self.assertEqual([expected],texts);self.assertFalse(c.get('span'))
        removals=[p for p in self.active if p.get('merge_into')==proposal['id']]
        self.assertEqual(1,len(removals));deletion=removals[0]
        self.assertEqual('source_merge',deletion['action']);self.assertEqual(1,deletion['end']-deletion['start'])
        consumed=self.first.blocks[deletion['start']]
        self.assertTrue(consumed.text.startswith('长期以来，我国的生猪存栏量'))
        self.assertFalse(consumed.images);self.assertFalse(consumed.heading)
        self.assertIn(consumed.text,expected)
        projected='\n'.join(self.projected_texts(self.first))
        self.assertEqual(1,projected.count(expected));self.assertEqual(1,projected.count('长期以来，我国的生猪存栏量'))
        self.assertNotIn('公司拥有完整的繁育体系，以引进曾祖代种猪作为素材',projected)
        # The original intervening figure is retained by the confirmed no-correspondence rule.
        for b in self.first.blocks[old.index+1:consumed.index]:
            self.assertEqual([],self.active_covering(self.first,b))
        figure=next(p for p in self.result['proposals'] if p.get('figure') and '肉猪养殖行业和公司肉猪养殖产业链' in p['heading'])
        self.assertEqual('keep',figure['decision'])
        self.assertEqual('no_correspondence_retained',figure['content_class'])


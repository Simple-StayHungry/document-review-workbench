def visible(element):
    """Independent text reader for original non-revised input objects."""
    output=[]
    def visit(node):
        if node.tag in ('{'+W+'}del','{'+W+'}moveFrom'):return
        if node.tag=='{'+W+'}t':output.append(node.text or '')
        for child in node:visit(child)
    visit(element)
    return ''.join(output)


def direct_paragraphs(path):
    with zipfile.ZipFile(path) as archive:
        root=E.fromstring(archive.read('word/document.xml'))
    return [visible(p) for p in root.find('{'+W+'}body').findall('{'+W+'}p')]


def file_record(path, role):
    return {'id':hashlib.sha256(path.read_bytes()).hexdigest(),'name':path.name,
            'path':str(path),'origin':str(path),'role':role,'aliases':[]}


class RealContentRegressionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        configured=os.environ.get('WORKBENCH_REAL_FIXTURES')
        cls.fixtures=Path(configured).expanduser().resolve() if configured else Path(__file__).resolve().parents[2]/'核查工作台_Codex交接包'
        if not cls.fixtures.is_dir():
            if configured:raise AssertionError('WORKBENCH_REAL_FIXTURES does not exist: '+str(cls.fixtures))
            raise unittest.SkipTest('Real handoff fixtures absent; set WORKBENCH_REAL_FIXTURES.')
        base=cls.fixtures/'02_示例项目A'
        source_paths=sorted((base/'01_正式来源').glob('*.docx'))
        if len(source_paths)!=2:raise AssertionError('Expected both supplied formal sources.')
        target_paths=[base/'02_原始底稿'/'核查记录及分析文件-第一章.docx',
                      base/'02_原始底稿'/'第二章 分析及核查记录.docx']
        cls.files=[file_record(p,'source') for p in source_paths]+[file_record(p,'target') for p in target_paths]
        cls.original_hashes={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in source_paths+target_paths}
        cls.engine=Engine();cls.result=cls.engine.analyze(cls.files,{'author':'柒'})
        cls.docs={f['id']:cls.engine.load(f) for f in cls.files}
        cls.targets=[cls.docs[f['id']] for f in cls.files if f['role']=='target']
        cls.source=next(d for d in cls.docs.values() if d.profile['kind']=='prospectus')
        cls.first=next(d for d in cls.targets if '第一章' in d.name)
        cls.active=[p for p in cls.result['proposals'] if p['decision'] in ('accept','same')]

    def active_covering(self, doc, block):
        return [p for p in self.active if p['target_id']==doc.hash and p['start']<=block.index<p['end']]

    def selected(self, proposal):
        candidate=proposal['candidates'][proposal['selected']]
        source=self.docs[candidate['doc_hash']]
        elements=[source.blocks[i].el for i in candidate.get('indices',range(candidate['start'],candidate['end']))]
        if candidate.get('span'):
            span=candidate['span']
            return candidate,[visible(source.blocks[span['block']].el)[span['start']:span['end']]]
        return candidate,[visible(e) for e in elements]

    def projected_texts(self, doc):
        active={};insertions={}
        for p in self.active:
            if p['target_id']!=doc.hash:continue
            if p.get('action')=='source_insert':
                self.assertEqual(p['start'],p['end'])
                insertions.setdefault(p['start'],[]).append(p)
            else:
                self.assertGreater(p['end'],p['start'])
                active[p['start']]=p
        texts=[];index=0
        while index<=len(doc.blocks):
            for p in insertions.get(index,[]):texts.extend(self.selected(p)[1])
            if index==len(doc.blocks):break
            proposal=active.get(index)
            if proposal:
                self.assertFalse(any(i in insertions for i in range(index+1,proposal['end'])),
                                 '新增正文不能隐含在另一替换范围内部')
                if proposal.get('action')!='source_merge':
                    texts.extend(self.selected(proposal)[1] if proposal['kind']=='material' else [proposal['new_text']])
                index=proposal['end']
            else:
                texts.append(visible(doc.blocks[index].el));index+=1
        return texts

    def test_personnel_in_both_chapters_copies_whole_current_paragraph(self):
        source_values=direct_paragraphs(self.source.path)
        expected=next(t for t in source_values if t.startswith('在人员委派方面'))
        self.assertIn(NEW_PERSONNEL,expected);self.assertNotIn(OLD_PERSONNEL,expected)
        for doc in self.targets:
            with self.subTest(chapter=doc.name):
                old=next(b for b in doc.blocks if b.text.startswith('在人员委派方面'))
                self.assertIn(OLD_PERSONNEL,old.text)
                proposals=self.active_covering(doc,old);self.assertEqual(1,len(proposals))
                c,texts=self.selected(proposals[0])
                self.assertIn(self.docs[c['doc_hash']].profile['kind'],('prospectus','opinion'));self.assertFalse(c.get('span'))
                self.assertIn(expected,texts)
                projected='\n'.join(self.projected_texts(doc))
                self.assertIn(NEW_PERSONNEL,projected);self.assertNotIn(OLD_PERSONNEL,projected)

    def test_three_independent_judgments_are_never_active(self):
        raw=direct_paragraphs(self.first.path)
        for sentence in PROTECTED_SENTENCES:
            with self.subTest(sentence=sentence[:20]):
                self.assertIn(sentence,raw)
                b=next(b for b in self.first.blocks if b.text==sentence)
                self.assertEqual([],self.active_covering(self.first,b));self.assertTrue(b.protected)
                self.assertIn(sentence,self.projected_texts(self.first))


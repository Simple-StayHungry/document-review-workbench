    def test_all_active_sources_are_current_formal_sources_with_no_partial_tables(self):
        for p in self.active:
            if p['kind']!='material':continue
            with self.subTest(proposal=p['id']):
                c=p['candidates'][p['selected']]
                selected_source=self.docs[c['doc_hash']]
                self.assertIn(selected_source.profile['kind'],('prospectus','opinion'))
                self.assertTrue(any(f['id']==selected_source.hash and f['role']=='source' for f in self.files))
                indices=c.get('indices',list(range(c['start'],c['end'])))
                self.assertEqual(len(indices),len(set(indices)))
                if any(selected_source.blocks[i].kind=='table' for i in indices):
                    self.assertFalse(c.get('span'))
                    for i in indices:
                        b=selected_source.blocks[i]
                        if b.kind=='table':self.assertEqual('{'+W+'}tbl',b.el.tag)

